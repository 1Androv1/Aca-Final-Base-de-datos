PROMPT CREANDO TRIGGER DE AUDITORIA
PROMPT ============================================================

CREATE OR REPLACE TRIGGER TRG_AUD_MATRICULAS
AFTER INSERT OR UPDATE OR DELETE ON MATRICULAS
FOR EACH ROW
DECLARE
    V_ACCION VARCHAR2(20);
    V_ID NUMBER;
    V_DETALLE VARCHAR2(500);
BEGIN
    IF INSERTING THEN
        V_ACCION := 'INSERT';
        V_ID := :NEW.ID;
        V_DETALLE := 'Registro de matricula creado para estudiante ID ' || :NEW.ESTUDIANTE_ID || ' y curso ID ' || :NEW.CURSO_ID;
    ELSIF UPDATING THEN
        V_ACCION := 'UPDATE';
        V_ID := :NEW.ID;
        V_DETALLE := 'Actualizacion de matricula. Estado anterior: ' || :OLD.ESTADO || ', estado nuevo: ' || :NEW.ESTADO;
    ELSIF DELETING THEN
        V_ACCION := 'DELETE';
        V_ID := :OLD.ID;
        V_DETALLE := 'Eliminacion de matricula para estudiante ID ' || :OLD.ESTUDIANTE_ID || ' y curso ID ' || :OLD.CURSO_ID;
    END IF;

    INSERT INTO AUDITORIA_MATRICULAS (
        MATRICULA_ID,
        ACCION,
        USUARIO_BD,
        FECHA_EVENTO,
        DETALLE
    )
    VALUES (
        V_ID,
        V_ACCION,
        USER,
        SYSTIMESTAMP,
        V_DETALLE
    );
END;

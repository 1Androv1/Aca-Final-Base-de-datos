PROMPT ============================================================

CREATE OR REPLACE PROCEDURE PR_REGISTRAR_MATRICULA (
    P_ESTUDIANTE_ID IN NUMBER,
    P_CURSO_ID IN NUMBER,
    P_NOTA_FINAL IN NUMBER DEFAULT NULL,
    P_ESTADO IN VARCHAR2 DEFAULT 'MATRICULADO'
)
IS
    V_EXISTE NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_EXISTE
    FROM MATRICULAS
    WHERE ESTUDIANTE_ID = P_ESTUDIANTE_ID
      AND CURSO_ID = P_CURSO_ID;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'El estudiante ya se encuentra matriculado en este curso.');
    END IF;

    INSERT INTO MATRICULAS (
        ESTUDIANTE_ID,
        CURSO_ID,
        NOTA_FINAL,
        ESTADO
    )
    VALUES (
        P_ESTUDIANTE_ID,
        P_CURSO_ID,
        P_NOTA_FINAL,
        P_ESTADO
    );

    COMMIT;
END;

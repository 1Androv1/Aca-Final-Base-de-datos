CREATE OR REPLACE VIEW VW_MATRICULAS_DETALLE AS
SELECT
    M.ID AS MATRICULA_ID,
    E.DOCUMENTO AS DOCUMENTO_ESTUDIANTE,
    E.NOMBRES || ' ' || E.APELLIDOS AS ESTUDIANTE,
    C.CODIGO AS CODIGO_CURSO,
    C.NOMBRE AS CURSO,
    D.NOMBRES || ' ' || D.APELLIDOS AS DOCENTE,
    M.FECHA_MATRICULA,
    M.NOTA_FINAL,
    M.ESTADO
FROM MATRICULAS M
INNER JOIN ESTUDIANTES E ON E.ID = M.ESTUDIANTE_ID
INNER JOIN CURSOS C ON C.ID = M.CURSO_ID
INNER JOIN DOCENTES D ON D.ID = C.DOCENTE_ID;

CREATE OR REPLACE VIEW VW_RESUMEN_CURSOS AS
SELECT
    C.ID AS CURSO_ID,
    C.CODIGO,
    C.NOMBRE,
    COUNT(M.ID) AS TOTAL_MATRICULAS,
    ROUND(AVG(M.NOTA_FINAL), 2) AS PROMEDIO_NOTAS
FROM CURSOS C
LEFT JOIN MATRICULAS M ON M.CURSO_ID = C.ID
GROUP BY C.ID, C.CODIGO, C.NOMBRE;


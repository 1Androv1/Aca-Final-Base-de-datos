CREATE TABLE ESTUDIANTES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    NOMBRES VARCHAR2(100) NOT NULL,
    APELLIDOS VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    TELEFONO VARCHAR2(20),
    FECHA_NACIMIENTO DATE NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_ESTUDIANTES PRIMARY KEY (ID),
    CONSTRAINT UQ_ESTUDIANTES_DOCUMENTO UNIQUE (DOCUMENTO),
    CONSTRAINT UQ_ESTUDIANTES_CORREO UNIQUE (CORREO)
);

CREATE TABLE DOCENTES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    NOMBRES VARCHAR2(100) NOT NULL,
    APELLIDOS VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    ESPECIALIDAD VARCHAR2(120) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_DOCENTES PRIMARY KEY (ID),
    CONSTRAINT UQ_DOCENTES_DOCUMENTO UNIQUE (DOCUMENTO),
    CONSTRAINT UQ_DOCENTES_CORREO UNIQUE (CORREO)
);

CREATE TABLE CURSOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODIGO VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(120) NOT NULL,
    CREDITOS NUMBER(2) NOT NULL,
    CUPO_MAXIMO NUMBER(4) NOT NULL,
    DOCENTE_ID NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_CURSOS PRIMARY KEY (ID),
    CONSTRAINT UQ_CURSOS_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_CURSOS_DOCENTE FOREIGN KEY (DOCENTE_ID) REFERENCES DOCENTES (ID),
    CONSTRAINT CK_CURSOS_CREDITOS CHECK (CREDITOS > 0),
    CONSTRAINT CK_CURSOS_CUPO CHECK (CUPO_MAXIMO > 0)
);

CREATE TABLE MATRICULAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ESTUDIANTE_ID NUMBER NOT NULL,
    CURSO_ID NUMBER NOT NULL,
    FECHA_MATRICULA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    NOTA_FINAL NUMBER(4,2),
    ESTADO VARCHAR2(20) DEFAULT 'MATRICULADO' NOT NULL,
    CONSTRAINT PK_MATRICULAS PRIMARY KEY (ID),
    CONSTRAINT FK_MATRICULAS_ESTUDIANTE FOREIGN KEY (ESTUDIANTE_ID) REFERENCES ESTUDIANTES (ID),
    CONSTRAINT FK_MATRICULAS_CURSO FOREIGN KEY (CURSO_ID) REFERENCES CURSOS (ID),
    CONSTRAINT UQ_MATRICULA_ESTUDIANTE_CURSO UNIQUE (ESTUDIANTE_ID, CURSO_ID),
    CONSTRAINT CK_MATRICULA_NOTA CHECK (NOTA_FINAL IS NULL OR (NOTA_FINAL >= 0 AND NOTA_FINAL <= 5))
);

CREATE TABLE AUDITORIA_MATRICULAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    MATRICULA_ID NUMBER NOT NULL,
    ACCION VARCHAR2(20) NOT NULL,
    USUARIO_BD VARCHAR2(80) DEFAULT USER NOT NULL,
    FECHA_EVENTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DETALLE VARCHAR2(500),
    CONSTRAINT PK_AUDITORIA_MATRICULAS PRIMARY KEY (ID)
);


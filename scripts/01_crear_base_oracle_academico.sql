CREATE OR REPLACE PROCEDURE SP_REGISTRAR_MATRICULA
(
	P_ESTUDIANTE_ID IN NUMBER,
	P_CURSO_ID IN NUMBER,
	P_MENSAJE OUT VARCHAR2
)
AS
	V_EXISTE NUMBER;
	V_CUPO_MAXIMO NUMBER;
	V_TOTAL_MATRICULADOS NUMBER;
BEGIN
	SELECT COUNT(*)
	INTO V_EXISTE
	FROM MATRICULAS
	WHERE ESTUDIANTE_ID = P_ESTUDIANTE_ID
	  AND CURSO_ID = P_CURSO_ID
	  AND ESTADO <> 'CANCELADO';

	IF V_EXISTE > 0 THEN
		P_MENSAJE := 'El estudiante ya se encuentra matriculado en este curso.';
		RETURN;
	END IF;

	SELECT CUPO_MAXIMO
	INTO V_CUPO_MAXIMO
	FROM CURSOS
	WHERE ID = P_CURSO_ID
	  AND ESTADO = 'ACTIVO';

	SELECT COUNT(*)
	INTO V_TOTAL_MATRICULADOS
	FROM MATRICULAS
	WHERE CURSO_ID = P_CURSO_ID
	  AND ESTADO <> 'CANCELADO';

	IF V_TOTAL_MATRICULADOS >= V_CUPO_MAXIMO THEN
		P_MENSAJE := 'No hay cupos disponibles para este curso.';
		RETURN;
	END IF;

	INSERT INTO MATRICULAS
	(
		ID,
		ESTUDIANTE_ID,
		CURSO_ID,
		FECHA_MATRICULA,
		ESTADO
	)
	VALUES
	(
		SEQ_MATRICULAS.NEXTVAL,
		P_ESTUDIANTE_ID,
		P_CURSO_ID,
		SYSDATE,
		'MATRICULADO'
	);

	P_MENSAJE := 'Matrícula registrada correctamente.';
	COMMIT;
EXCEPTION
	WHEN NO_DATA_FOUND THEN
		P_MENSAJE := 'No se encontró el estudiante o el curso indicado.';
	WHEN OTHERS THEN
		ROLLBACK;
		P_MENSAJE := 'Error al registrar matrícula: ' || SQLERRM;
END;
/

CREATE OR REPLACE FUNCTION FN_TOTAL_CREDITOS_ESTUDIANTE
(
	P_ESTUDIANTE_ID IN NUMBER
)
RETURN NUMBER
AS
	V_TOTAL_CREDITOS NUMBER;
BEGIN
	SELECT NVL(SUM(C.CREDITOS), 0)
	INTO V_TOTAL_CREDITOS
	FROM MATRICULAS M
	INNER JOIN CURSOS C ON C.ID = M.CURSO_ID
	WHERE M.ESTUDIANTE_ID = P_ESTUDIANTE_ID
	  AND M.ESTADO <> 'CANCELADO';

	RETURN V_TOTAL_CREDITOS;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDITORIA_MATRICULAS
AFTER INSERT OR UPDATE OR DELETE ON MATRICULAS
FOR EACH ROW
DECLARE
	V_ACCION VARCHAR2(20);
	V_MATRICULA_ID NUMBER(10);
	V_DETALLE VARCHAR2(500);
BEGIN
	IF INSERTING THEN
		V_ACCION := 'INSERT';
		V_MATRICULA_ID := :NEW.ID;
		V_DETALLE := 'Se registró matrícula del estudiante ' || :NEW.ESTUDIANTE_ID || ' en el curso ' || :NEW.CURSO_ID;
	ELSIF UPDATING THEN
		V_ACCION := 'UPDATE';
		V_MATRICULA_ID := :NEW.ID;
		V_DETALLE := 'Cambio de estado: ' || :OLD.ESTADO || ' -> ' || :NEW.ESTADO;
	ELSE
		V_ACCION := 'DELETE';
		V_MATRICULA_ID := :OLD.ID;
		V_DETALLE := 'Se eliminó matrícula del estudiante ' || :OLD.ESTUDIANTE_ID || ' en el curso ' || :OLD.CURSO_ID;
	END IF;

	INSERT INTO AUDITORIA_MATRICULAS
	(
		ID,
		MATRICULA_ID,
		ACCION,
		USUARIO_BD,
		FECHA_EVENTO,
		DETALLE
	)
	VALUES
	(
		SEQ_AUDITORIA_MATRICULAS.NEXTVAL,
		V_MATRICULA_ID,
		V_ACCION,
		USER,
		SYSDATE,
		V_DETALLE
	);
END;
/


	CONSTRAINT UQ_CURSOS_CODIGO UNIQUE (CODIGO),
	CONSTRAINT FK_CURSOS_DOCENTES FOREIGN KEY (DOCENTE_ID) REFERENCES DOCENTES(ID),
	CONSTRAINT CK_CURSOS_CREDITOS CHECK (CREDITOS BETWEEN 1 AND 6),
	CONSTRAINT CK_CURSOS_CUPO CHECK (CUPO_MAXIMO > 0),
	CONSTRAINT CK_CURSOS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE MATRICULAS
(
	ID NUMBER(10) NOT NULL,
	ESTUDIANTE_ID NUMBER(10) NOT NULL,
	CURSO_ID NUMBER(10) NOT NULL,
	FECHA_MATRICULA DATE DEFAULT SYSDATE NOT NULL,
	NOTA_FINAL NUMBER(4,2),
	ESTADO VARCHAR2(20) DEFAULT 'MATRICULADO' NOT NULL,
	CONSTRAINT PK_MATRICULAS PRIMARY KEY (ID),
	CONSTRAINT FK_MATRICULAS_ESTUDIANTES FOREIGN KEY (ESTUDIANTE_ID) REFERENCES ESTUDIANTES(ID),
	CONSTRAINT FK_MATRICULAS_CURSOS FOREIGN KEY (CURSO_ID) REFERENCES CURSOS(ID),
	CONSTRAINT UQ_MATRICULA_ESTUDIANTE_CURSO UNIQUE (ESTUDIANTE_ID, CURSO_ID),
	CONSTRAINT CK_MATRICULAS_NOTA CHECK (NOTA_FINAL IS NULL OR NOTA_FINAL BETWEEN 0 AND 5),
	CONSTRAINT CK_MATRICULAS_ESTADO CHECK (ESTADO IN ('MATRICULADO', 'APROBADO', 'REPROBADO', 'CANCELADO'))
